import { expect, it } from 'vitest'
import { MetricLimitError, MetricRegistry, MetricsClosedError } from './metrics.js'
import { renderPrometheus } from './prometheus.js'
it('records counters/gauges/cumulative histograms and renders escaped Prometheus text', () => {
  const metrics = new MetricRegistry()
  const counter = metrics.counter({ name: 'requests_total', help: 'Requests\\completed\nnow.', labelNames: ['route'] })
  counter.add(2, { route: '/items/:id' }); counter.add(1, { route: '/items/:id' })
  const gauge = metrics.gauge({ name: 'active', help: 'Active.' }); gauge.set(2); gauge.set(0)
  const histogram = metrics.histogram({ name: 'latency_seconds', help: 'Latency.', labelNames: ['route'], buckets: [0, 1, 2] })
  for (const value of [0, 0.5, 2, 3]) histogram.record(value, { route: 'a"b\\c\nd' })
  const text = renderPrometheus(metrics.snapshot())
  expect(text).toContain('# HELP requests_total Requests\\\\completed\\nnow.\n# TYPE requests_total counter\n')
  expect(text).toContain('requests_total{route="/items/:id"} 3\n')
  expect(text).toContain('active 0\n')
  const sample = metrics.snapshot().find((metric) => metric.name === 'latency_seconds')!.series[0]!
  expect(sample).toMatchObject({ count: 4, sum: 5.5, buckets: [1, 2, 3] })
  expect(text).toContain('latency_seconds_bucket{route="a\\"b\\\\c\\nd",le="+Inf"} 4\n')
  expect(text.endsWith('\n')).toBe(true)
})
it('bounds definitions/series and still allows updates to existing time series', () => {
  const metrics = new MetricRegistry({ maxMetrics: 2, maxSeriesPerMetric: 1, maxTotalSeries: 1 })
  const counter = metrics.counter({ name: 'bounded', help: 'Bounded.', labelNames: ['key'] })
  counter.add(1, { key: 'one' })
  expect(() => counter.add(1, { key: 'two' })).toThrow(MetricLimitError)
  counter.add(2, { key: 'one' })
  const other = metrics.gauge({ name: 'other', help: 'Other.' })
  expect(() => other.set(1)).toThrow(MetricLimitError)
  expect(() => metrics.counter({ name: 'third', help: 'Third.' })).toThrow(MetricLimitError)
  expect(metrics.snapshot()[0]?.series[0]?.value).toBe(3)
  expect(metrics.stats()).toMatchObject({ metrics: 2, series: 1 })
})
it('rejects invalid identities/labels/value transitions and reserves derived histogram names', () => {
  const metrics = new MetricRegistry()
  const counter = metrics.counter({ name: 'count', help: 'Count.', labelNames: ['route'] })
  for (const value of [-1, Number.NaN, Infinity]) expect(() => counter.add(value, { route: 'a' })).toThrow()
  expect(() => counter.add(1, {} as never)).toThrow('labels')
  expect(() => counter.add(1, { route: 'a', extra: 'b' } as never)).toThrow('labels')
  metrics.histogram({ name: 'timing', help: 'Timing.', buckets: [1, 2] })
  expect(() => metrics.counter({ name: 'timing_count', help: 'Collision.' })).toThrow('already exists')
  expect(() => metrics.histogram({ name: 'other', help: 'Other.', buckets: [2, 1] })).toThrow('ascending')
  expect(() => metrics.gauge({ name: 'bad-name', help: 'Invalid.' })).toThrow('name')
  expect(() => metrics.gauge({ name: true as never, help: 'Invalid.' })).toThrow('name')
  expect(() => metrics.gauge({ name: 'invalid_help', help: 42 as never })).toThrow('help')
  expect(() => metrics.gauge({ name: 'invalid_labels', help: 'Invalid.', labelNames: 'route' as never })).toThrow('labels')
  expect(() => metrics.histogram({ name: 'bad', help: 'Bad.', labelNames: ['le'] })).toThrow('labels')
})
it('keeps snapshots detached and preserves final snapshots after close', () => {
  const metrics = new MetricRegistry(), gauge = metrics.gauge({ name: 'count', help: 'Count.' })
  gauge.set(2)
  const snapshot = metrics.snapshot()
  ;(snapshot[0]!.series[0] as { value: number }).value = 999
  expect(metrics.snapshot()[0]!.series[0]!.value).toBe(2)
  metrics.close(); metrics.close()
  expect(() => gauge.set(1)).toThrow(MetricsClosedError)
  expect(metrics.snapshot()[0]!.series[0]!.value).toBe(2)
})
